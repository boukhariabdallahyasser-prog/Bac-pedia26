import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import vm from 'node:vm';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const syntax=spawnSync(process.execPath,['--check','assets/weekly-planner.js'],{encoding:'utf8'});
assert.equal(syntax.status,0,syntax.stderr);
const c={window:{},console,URL,document:{readyState:'loading',addEventListener(){}},Intl,Date};
vm.runInNewContext(read('assets/education-model.js'),c,{timeout:2000});
vm.runInNewContext(read('assets/subject-taxonomy.js'),c,{timeout:2000});
vm.runInNewContext(read('assets/weekly-planner.js'),c,{timeout:2000});
const api=c.window.BacWeeklyPlanner;
assert.equal(typeof api.buildPlan,'function');
const manifest=JSON.parse(read('resources.json'));
const subjects=c.window.BacEducation.list('math');
const models=c.window.BacSubjectCatalog.build({manifest,branch:'math',subBranch:null,subjects}).filter(x=>x.items.length);
assert.ok(models.length>=2);
const short=api.buildPlan(models.slice(0,2),3,25);
assert.equal(short.length,3);assert.ok(short.every(x=>x.tasks.length===1));
const long=api.buildPlan(models.slice(0,2),7,75);
assert.equal(long.length,7);assert.ok(long.every(x=>x.tasks.length===3));
assert.ok(long.every(x=>x.dateKey&&x.label&&x.subject&&x.date instanceof Date));
const sourceUrls=new Set(models.flatMap(m=>m.items.map(x=>x.url)));
const sourceTitles=new Set(models.flatMap(m=>m.items.map(x=>x.title)));
for(const day of long)for(const task of day.tasks){
 assert.ok(sourceUrls.has(task.url),'Study plan invented a resource URL: '+task.url);
 assert.ok(sourceTitles.has(task.title),'Study plan invented a resource title: '+task.title);
 assert.equal(task.minutes,25);
 assert.ok(task.id.includes(task.subjectId));
}
assert.equal(new Set(long.flatMap(day=>day.tasks.map(x=>x.id))).size,21,'Duplicate planner tasks');
const html=read('student/index.html');
assert.match(html,/id="weeklyStudioDisclosure"/);
assert.match(html,/id="weeklyStudio"/);
assert.match(html,/assets\/weekly-planner\.css/);
assert.match(read('src/main.js'),/assets\/weekly-planner\.js/);
assert.match(read('vite.config.js'),/assets\/weekly-planner\.css/);
const frontend=read('assets/legacy-app.js');
assert.match(frontend,/BacWeeklyPlanner\?\.refresh/);
assert.match(frontend,/function renderTasks\(\)/);
assert.match(read('assets/weekly-planner.js'),/studyPlanKey/);
console.log('Weekly plan generates real-source tasks across 3/5/7 day schedules without inventing resources.');
